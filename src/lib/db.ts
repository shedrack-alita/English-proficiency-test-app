import "server-only";
import fs from "node:fs";
import path from "node:path";
import { BANK_VERSION, seed } from "./seed";

/*
 * Storage is Postgres:
 * - Hosted (Vercel, Netlify etc.): set DATABASE_URL to a Neon connection string.
 * - Local development: falls back to PGlite (Postgres compiled to WebAssembly) in data/pglite.
 * Queries are written with "?" placeholders, converted to Postgres "$1, $2, ..." below.
 */

const NOW_TEXT = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

const SCHEMA = `
CREATE TABLE IF NOT EXISTS meta (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS admins (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL
);

-- Emails are stored in lower case. created_at is UTC text: "YYYY-MM-DD HH:MM:SS".
CREATE TABLE IF NOT EXISTS candidates (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  gender        TEXT NOT NULL DEFAULT '',
  course        TEXT NOT NULL DEFAULT '',
  department    TEXT NOT NULL DEFAULT '',
  birthdate     TEXT NOT NULL DEFAULT '',
  access        TEXT NOT NULL DEFAULT 'both' CHECK (access IN ('both','official','practice')),
  status        TEXT NOT NULL DEFAULT 'active',
  created_at    TEXT NOT NULL DEFAULT ${NOW_TEXT}
);

-- official: timed, one attempt, admin-set limits. practice: unlimited, candidate picks limits.
CREATE TABLE IF NOT EXISTS tests (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          TEXT NOT NULL UNIQUE,
  category       TEXT NOT NULL DEFAULT '',
  description    TEXT NOT NULL DEFAULT '',
  kind           TEXT NOT NULL CHECK (kind IN ('official','practice')),
  time_limit     INTEGER NOT NULL DEFAULT 0,
  question_limit INTEGER NOT NULL DEFAULT 0,
  shuffle        INTEGER NOT NULL DEFAULT 1,
  position       INTEGER NOT NULL DEFAULT 0,
  builtin        INTEGER NOT NULL DEFAULT 0,
  created_at     TEXT NOT NULL DEFAULT ${NOW_TEXT}
);

-- **text** in prompt/choices marks words that are underlined in the printed paper.
CREATE TABLE IF NOT EXISTS questions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  test_id     INTEGER NOT NULL REFERENCES tests(id) ON DELETE CASCADE,
  position    INTEGER NOT NULL DEFAULT 0,
  topic       TEXT NOT NULL DEFAULT '',
  instruction TEXT NOT NULL DEFAULT '',
  passage     TEXT NOT NULL DEFAULT '',
  prompt      TEXT NOT NULL DEFAULT '',
  choice_a    TEXT NOT NULL,
  choice_b    TEXT NOT NULL,
  choice_c    TEXT NOT NULL,
  choice_d    TEXT NOT NULL,
  answer      TEXT NOT NULL CHECK (answer IN ('A','B','C','D')),
  explanation TEXT NOT NULL DEFAULT '',
  tip         TEXT NOT NULL DEFAULT '',
  source      TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS questions_test ON questions(test_id, position);

-- One row per sitting. Times are epoch milliseconds; question_ids is a JSON array.
CREATE TABLE IF NOT EXISTS attempts (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  test_id      INTEGER NOT NULL REFERENCES tests(id) ON DELETE CASCADE,
  question_ids TEXT NOT NULL,
  started_at   BIGINT NOT NULL,
  expires_at   BIGINT NOT NULL,
  submitted_at BIGINT,
  score        INTEGER,
  total        INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS attempts_candidate ON attempts(candidate_id, test_id);

CREATE TABLE IF NOT EXISTS attempt_answers (
  attempt_id  INTEGER NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
  question_id INTEGER NOT NULL,
  choice      TEXT NOT NULL CHECK (choice IN ('A','B','C','D')),
  PRIMARY KEY (attempt_id, question_id)
);

CREATE TABLE IF NOT EXISTS feedbacks (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  display_name TEXT NOT NULL,
  message      TEXT NOT NULL,
  created_at   TEXT NOT NULL DEFAULT ${NOW_TEXT}
);
`;

export type Row = Record<string, unknown>;
export type Args = unknown[];

/** Anything that can run a statement: the database itself or an open transaction. */
export type Executor = {
  query(sql: string, params?: Args): Promise<{ rows: Row[]; rowCount: number }>;
};

export type Database = Executor & {
  /** Runs several statements with no parameters (the schema). */
  exec(sql: string): Promise<void>;
  transaction<T>(fn: (tx: Executor) => Promise<T>): Promise<T>;
};

// BIGINT (epoch ms, COUNT) and NUMERIC (AVG) come back as strings by default; all values here fit in a JS number.
const INT8 = 20;
const NUMERIC = 1700;

async function neonDatabase(connectionString: string): Promise<Database> {
  const { Pool, neonConfig, types } = await import("@neondatabase/serverless");
  const { default: ws } = await import("ws");
  neonConfig.webSocketConstructor = ws;
  types.setTypeParser(INT8, Number);
  types.setTypeParser(NUMERIC, Number);
  const pool = new Pool({ connectionString, max: 5, idleTimeoutMillis: 10_000 });
  // Neon closes idle connections; the pool drops them and opens new ones on the next query.
  pool.on("error", (error: Error) => console.error("Postgres connection error:", error.message));

  const executor = (client: Pick<typeof pool, "query">): Executor => ({
    async query(sql, params = []) {
      const rs = await client.query(sql, params);
      return { rows: rs.rows as Row[], rowCount: rs.rowCount ?? 0 };
    },
  });
  return {
    ...executor(pool),
    async exec(sql) {
      await pool.query(sql);
    },
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const result = await fn(executor(client));
        await client.query("COMMIT");
        return result;
      } catch (error) {
        await client.query("ROLLBACK").catch(() => {});
        throw error;
      } finally {
        client.release();
      }
    },
  };
}

async function localDatabase(): Promise<Database> {
  const dir = process.env.EPT_DB_PATH ?? path.join(process.cwd(), "data", "pglite");
  fs.mkdirSync(dir, { recursive: true });
  const { PGlite } = await import("@electric-sql/pglite");
  const db = await PGlite.create(dir, { parsers: { [INT8]: Number, [NUMERIC]: Number } });

  const executor = (client: Pick<typeof db, "query">): Executor => ({
    async query(sql, params = []) {
      const rs = await client.query<Row>(sql, params);
      return { rows: rs.rows, rowCount: rs.affectedRows ?? 0 };
    },
  });
  return {
    ...executor(db),
    async exec(sql) {
      await db.exec(sql);
    },
    transaction: (fn) => db.transaction((tx) => fn(executor(tx))),
  };
}

async function createDatabase(): Promise<Database> {
  const url = process.env.DATABASE_URL || process.env.POSTGRES_URL;
  if (url) return neonDatabase(url);
  if (process.env.NETLIFY || process.env.VERCEL) {
    throw new Error("DATABASE_URL is not set. Add your Neon connection string to the site's environment variables.");
  }
  return localDatabase();
}

async function open() {
  const db = await createDatabase();
  await db.exec(SCHEMA);
  await seed(db);
  return db;
}

// One database per server instance, created on first use and reused across hot reloads in development.
const globalForDb = globalThis as unknown as { eptPg?: Promise<Database>; eptPgBankVersion?: string };

export function getDb() {
  let pending: Promise<Database> | undefined;
  if (!globalForDb.eptPg) {
    pending = open();
  } else if (globalForDb.eptPgBankVersion !== BANK_VERSION) {
    // The database survives hot reloads in development; when new built-in content arrives,
    // re-run the schema and seed so it is installed without restarting the server.
    pending = globalForDb.eptPg.then(async (db) => {
      await db.exec(SCHEMA);
      await seed(db);
      return db;
    });
  }
  if (pending) {
    globalForDb.eptPgBankVersion = BANK_VERSION;
    globalForDb.eptPg = pending.catch((error) => {
      globalForDb.eptPg = undefined; // retry on the next request
      throw error;
    });
  }
  return globalForDb.eptPg!;
}

/** Converts "?" placeholders (outside quoted strings) to Postgres "$1, $2, ...". */
export function toPg(sql: string) {
  let n = 0;
  let quoted = false;
  let out = "";
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === "?" && !quoted ? `$${++n}` : ch;
  }
  return out;
}

export async function all(sql: string, args: Args = [], ex?: Executor): Promise<Row[]> {
  return (await (ex ?? (await getDb())).query(toPg(sql), args)).rows;
}

export async function get(sql: string, args: Args = [], ex?: Executor): Promise<Row | undefined> {
  return (await all(sql, args, ex))[0];
}

export async function run(sql: string, args: Args = [], ex?: Executor) {
  const rs = await (ex ?? (await getDb())).query(toPg(sql), args);
  return { rowsAffected: rs.rowCount };
}

export async function transaction<T>(fn: (tx: Executor) => Promise<T>): Promise<T> {
  return (await getDb()).transaction(fn);
}
